        // **물질의 85%가 암흑물질이다** — 실제 우주의 비율이고, 거대구조를 실제로
        // 짜는 것이 그쪽이다. 보통 물질은 그 그물을 따라 흘러 들어갈 뿐이다.
        // 암흑물질은 빛 모드에서 안 보이므로 이 장면은 밀도로 본다(호출부에서 정한다).
