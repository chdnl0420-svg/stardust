    //
    // 여기서 보려는 것은 은하 하나가 아니라 **암흑물질이 중력만으로 짜 내는 그물**이다.
    // 그래서 은하 장면과 켜는 것이 정반대다 — 가스 물리를 전부 끄고 중력만 남긴다.
