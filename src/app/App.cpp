    cfg.contactEnabled = false;
    // 식히기는 켠 채로 시작한다. 꺼 두면 중력으로 모인 것이 그 자리에서 데워져 도로
    // 흩어지기만 해 **어느 장면에서도 아무것도 뭉치지 않는다** — 모였다 흩어졌다만
    // 되풀이한다(2026-08-14 실측: 켜면 최대밀도 6771 → 94483, 점유 셀 273876 → 15440).
