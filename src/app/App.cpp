    cfg.coolingEnabled = true;

    // 경계 — 은하 장면은 텅 빈 우주에 홀로 떠 있어야 하고(고립),
    //        우주 구조 형성은 반대편으로 이어지는 우주가 표준이다(주기).
    //
    // **은하 장면을 주기로 바꿨다가 되돌렸다(2026-08-16).** 고립 경계가 판 끝에서
    // 알갱이를 붙잡고 속도를 0.25배로 죽이는 것이 화면에서 「보이지 않는 벽에 튕김」으로
    // 보인다는 지적을 받고 바꿨는데, **주기 경계에서는 은하가 아예 안 뭉친다.**
    //
    // 주기 푸아송 풀이는 **평균 밀도를 배경으로 빼고 요동만 중력을 만든다** — 안 그러면
    // k=0 모드가 발산한다. 우주 구조를 볼 때는 그것이 옳지만, **은하 하나가 판의 작은
    // 부분일 때는 그 은하의 자기중력이 대부분 깎여 나간다.**
    //
    // 2026-08-16 실측(20만, simTime 13.5 까지, 경계 × 냉각 2×2):
    //
    //   조건            maxSpeed   maxDensity
    //   주기 + 냉각      0.0004     1,370      ← 완전히 멈춘다
    //   고립 + 냉각      0.2708    29,768
    //   주기 · 냉각 끔   0.0518     1,285
    //   고립 · 냉각 끔   0.2388       551
    //
    // **주기에서 최대밀도가 23분의 1 이다** — 뭉치지 않는다는 뜻이고, 거기에 냉각이
    // 남은 운동마저 걷어내면 판이 통째로 얼어붙는다. 처음 80초만 보면 멀쩡해 보여서
    // 그때는 못 봤다.
    //
    // 벽에 튕기는 것을 고치려면 경계가 아니라 **그 벽에 닿지 않게** 해야 한다.
    cfg.boundary = Boundary::Isolated;

    // 압력 — **켠다(2026-08-16).**
    //
    // 옛 주석은 "무압력 중력계에서 나오는 현상이라 끄는 쪽이 선명하다"였는데, 그때
    // `pressureEnabled` 는 **코어에서 한 번도 안 쓰이는 플래그**였다(2026-08-16 실측: 사용 0회).
    // 즉 「끈 쪽이 선명하다」는 것은 미구현 플래그를 끈 것이고, 실제로 압력 노릇을 하던 것은
    // `orbitDispersion` 이라는 손으로 정한 숫자였다.
    //
    // 이제 속도 분산 텐서가 실제로 돌고 `orbitDispersion` 은 지웠다(2026-08-18). **둘은 한
    // 몸이라 같이 바뀌어야 한다** — 압력을 끈 채 난수만 빼면 원반을 붙잡는 것이 아무것도 없다.
    cfg.pressureEnabled = true;

    // 별 형성 — **켠다(2026-08-16).**
    //
    // 코어 기본값이 `false` 라(`Sim.h` `starFormationEnabled`) 프리셋이 안 켜면 **앱을 열어
    // 그냥 두었을 때 별이 하나도 안 생긴다.** 2026-08-16 실측에서 100초를 돌려도 `starCount`
    // 가 0 이었다 — 이 판이 만든 것(별의 한살이·초신성·재 사슬·흑체 색)이 통째로 안 보인다.
    // 스물다섯 바퀴 동안 못 봤던 것은 측정 스크립트가 매번 `starFormation=1` 을 명시해
    // 켜고 잰 탓이다. **스크립트가 켜 주는 것은 사용자가 보는 것이 아니다.**
    //
    // **우주 구조 형성 장면도 켠다(2026-08-17). 예외를 없앴다.**
    //
    // 껐던 이유는 「거기서 보려는 것은 격자 규모의 필라멘트이지 개별 별이 아니고, 별이
    // 되면 그 알갱이는 더 안 뭉쳐 구조가 흐려진다」였다. 그것을 실측으로 다시 봤다
    // (round-46) — 그때는 별 형성 효율이 0.02 였고 지금은 0.005 다.
    //
    // 수치만 보면 여전히 나쁘다: 점유 셀이 29,891 → 430,422(14배)로 퍼지고 최대 밀도가
    // 108,985 → 48,367 로 절반이 된다. **그런데 그림이 그 수치를 뒤집었다** —
    // 필라멘트가 **더 선명하다**(`scratchpad/r46-web-on.png`). 가스가 반사성운으로 빛나
    // 거대 구조가 청록으로 드러나고, 그 안에 별과 은하와 블랙홀 강착원반이 보인다.
    //
    // **점유 셀은 「퍼짐」이지 「구조」가 아니었다** — 내가 자를 잘못 댔다. 사용자가 처음에
    // 말한 「별들이 모여서 은하가 되는 걸 보고싶어」에 가장 가까운 그림이 여기서 나온다.
    cfg.starFormationEnabled = true;

    // 별이 무너져 블랙홀이 되는 것 — **켠다(2026-08-17).**
    //
    // 2026-08-16 에 껐던 이유는 블랙홀 여덟이 알갱이의 96%를 삼켜 판이 비었기 때문이다.
    // 그때는 삼킴에 상한이 없었다 — 뭉친 칸 하나에 91만 개가 몰리는데 그 자리에 블랙홀이
    // 생기면 한 스텝에 다 빨려 들었다(실측: 시뮬 시간 2 만에 83만 개).
    //
    // **빠져 있던 현실은 에딩턴 강착 한계였다.** 실제 블랙홀은 아무리 물질이 많아도
    // 무한정 못 삼킨다 — 떨어지는 물질이 내는 복사압이 그 이상의 유입을 밀어내고, 못
    // 들어간 것은 둘레를 돌며 기다린다. 그 대기열이 강착원반이다(`packBH` 의 셋째 칸).
    // 넣고 재니 같은 시각의 삼킨 수가 832,759 → 66,669 로 **133분의 1** 이 됐고 판이
    // 계속 돌았다.
    //
    // 사용자 요청이 「별이 붕괴돼서 블랙홀이 되는 것도 보고싶어」이고, 끄면 그것을 볼
    // 방법이 없다. 우주 구조 형성 장면도 같이 켠다 — 거기서도 별이 생기고, 실측에서
    // 강착원반이 필라멘트 사이에 보였다(round-46).
    cfg.starCollapseToBH = true;
