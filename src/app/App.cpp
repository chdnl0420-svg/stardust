        // 사용자가 전에 설정 창에서 전자기력을 켜 두었으면 필라멘트 장면에서도 켜진 채로
        // 돌고, 그러면 「중력만으로 짜인 그물」이 아니라 전하가 밀고 당긴 무언가가 된다.
