// 사고 기록 — 시스템이 통째로 죽어도 남는 로그.
//
// 이 앱의 사고는 앱이 죽는 것으로 끝나지 않는다. 그래픽 드라이버가 타임아웃되고
// 그 리셋이 실패하면 윈도우가 재부팅된다. 그러면 **평범한 로그는 통째로 사라진다** —
// fprintf 는 CRT 버퍼에, fflush 는 OS 캐시에만 넣기 때문이다. 디스크에 실제로
// 닿는 것은 _commit 뿐이고, 사고 직전 몇 줄을 남기려면 그것까지 해야 한다.
//
// 그래서 두 단계로 쓴다.
//   line()  — CRT 버퍼만 비운다(싸다). 흐름을 남기는 용도
//   mark()  — 디스크까지 민다(비싸다, 수 ms). 사고 직전에 알고 싶은 것만
//
// 층 규칙: 여기는 Win32 를 쓰지 않는다(CRT 만). 그래야 Core 층(Sim.cu)에도 링크되어
// 커널 시간처럼 정작 사고를 설명하는 값을 코어가 직접 적을 수 있다.
#pragma once

namespace fx {

// 세션을 연다. 로그 파일을 만들고 머리말(카드·드라이버·VRAM)을 적는다.
// 직전 세션이 정상 종료 표시 없이 끝났으면 그 사실을 맨 위에 적는다 — 재부팅으로
// 죽으면 종료 코드도 예외도 남지 않으므로, 「표시가 없다」가 유일한 증거다.
void begin(const char* version);

// 흐름 기록. CRT 버퍼만 비운다.
void line(const char* fmt, ...);

// 사고 직전에 알고 싶은 것. 디스크까지 민다.
// 설정 변경·재할당·형태 놓기·위험 감지처럼 「이것 직후에 죽었다」가 뜻을 갖는 자리에만 쓴다.
void mark(const char* fmt, ...);

// 정상 종료. 표시 파일을 지운다 — 이게 지워져 있으면 다음 실행이 「정상이었다」로 읽는다.
void endOk();

// 직전 세션이 비정상 종료(재부팅·강제종료)됐는가. begin() 뒤에 유효하다.
bool lastSessionCrashed();

// 이번 세션 로그 파일의 전체 경로. 설정 화면이 사용자에게 보여 준다.
const char* logPath();

// 로그가 쌓인 폴더. 「사고 기록 열기」가 탐색기로 연다.
const char* logDir();

} // namespace fx
