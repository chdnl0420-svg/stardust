    // 조합이 있고, 그 상태에서 알갱이가 한곳에 몰리면 커널 하나가 드라이버 타임아웃(2초)을
    // 넘겨 시스템이 재부팅된다(2026-08-14 실측: 480만 알갱이 + 256³ 격자 + 블랙홀).
