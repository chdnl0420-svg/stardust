    static size_t      estimateBytes(int particleCount, int gridSize, Boundary boundary);
    // 가용 VRAM 안에 들어가는 최대 파티클 수. 요청이 넘치면 이 값으로 잘라 쓴다.
    static int         maxParticlesFor(int gridSize, Boundary boundary, size_t freeBytes);

