#pragma once

#include <string>

// 초기조건 프리셋. 각 값이 파티클을 어디에 어떤 속도로 놓을지를 정한다.
enum class Preset {
    SpiralDisk,   // 나선 은하 하나 — 처음부터 나선팔 모양으로 깐다
    TidalPair,    // 나선 은하 둘이 양옆에서 서로를 끌어당긴다
    CosmicWeb,    // 균일 난수 + 미세 요동 — 우주 거대구조가 자란다
    BlackHole,    // 중심에 블랙홀 — 휘어진 시공간의 최단경로를 따라 돈다
    Empty,        // 빈 판. 마우스로 직접 만든다
};

// 판 바깥을 어떻게 다루는가.
//  Isolated : 텅 빈 우주에 홀로 떠 있다(은하 시나리오). 격자를 2배로 패딩해 푼다 — 비용 4배
//  Periodic : 반대편으로 넘어간다(우주론 표준). 가장 싸다
enum class Boundary { Isolated, Periodic };

// 2D 격자에서 어떤 중력을 재현할지.
//  InverseSquare : 3D 우주를 위에서 눌러 본 느낌(힘 ∝ 1/r²). 주파수공간에서 1/k 를 곱한다
//  InverseR      : 수학적으로 올바른 2D 중력(힘 ∝ 1/r). 1/k² 를 곱한다. 판 전체가 한 덩어리로 붕괴한다
enum class GravityLaw { InverseSquare, InverseR };

// 시뮬 시간 1단위가 실제로 몇 년인가.
//
// 이 앱의 `dt` 는 CFL 안정성이 정하는 **무차원** 값이라 그 자체로는 「년」이 아니다.
// 별의 수명·나이를 실제 천문 값(태양급 100억 년, 20배 별 1000만 년)으로 다루려면
// 시뮬 시간과 년 사이의 환율이 하나 있어야 하고, 그것이 이 상수다.
//
// **값의 근거 — dt 를 건드려 맞춘 것이 아니라 지금 dt 에서 역산했다.**
//   timeScale=1 일 때 한 스텝 dt = 0.0016, 초당 60프레임 → 실시간 1초 = 시뮬 0.096 단위
//   0.096 × 1000만 년 = 96만 년 ≈ 「실시간 1초 = 100만 년」(오차 4%)
//
// 이 환율에서 세 가지가 다 담긴다:
//   은하 한 바퀴 2억 년 → 208초 · 무거운 별 한 살이 1000만 년 → 10.4초 · 태양급 100억 년 → 2.9시간
//
// **딱 하나가 안 담긴다: 초신성.** 실제로 몇 초라 이 환율에서 한 프레임의 2000억분의 1 이다.
// 배율을 어떻게 잡아도 초와 억 년은 13자리 차이라 한 손잡이로는 절대 안 만난다 —
// 그래서 폭발만은 시뮬 시간에서 떼어내 **보이는 길이로 따로 늘린다**(kExplode 쪽에서 다룬다).
//
// `dt` 자체를 바꿔 환율을 맞추지 않는 이유: dt 는 안정성이 쥔 값이라
// 그것을 표시 편의로 움직이면 안정성 근거가 통째로 사라진다(Sim::step 의 CFL 주석 참조).
constexpr double kYearsPerSimUnit = 1.0e7;

