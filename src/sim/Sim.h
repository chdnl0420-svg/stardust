    // **태양급 별 하나가 알갱이 몇 개인가.** 수명·최후를 가르는 기준이 이 값이다 —
    // 질량비 `M/starSunMass` 가 8 아래면 백색왜성, 그 위면 터진다.
    // 알갱이 하나가 태양 하나가 아니라 가스 덩어리라 이 값은 실측으로 눈금을 잡는다.
